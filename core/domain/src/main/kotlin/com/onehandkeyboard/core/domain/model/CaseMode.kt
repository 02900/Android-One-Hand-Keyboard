package com.onehandkeyboard.core.domain.model

/**
 * Enum para los modos de mayúsculas/minúsculas del teclado
 *
 * Define los diferentes modos de capitalización disponibles:
 * - LOWERCASE: Todo en minúsculas
 * - UPPERCASE: Todo en mayúsculas
 * - CAPITALIZE: Primera letra de cada palabra en mayúscula
 */
enum class CaseMode {
    LOWERCASE,
    UPPERCASE,
    CAPITALIZE,
}
